/**
 * Thuật toán tính khoảng cách chỉnh sửa Levenshtein cực nhanh (O(N*M))
 */
export const fastLevenshtein = (s1, s2) => {
  if (s1 === s2) return 0;
  if (!s1) return s2 ? s2.length : 0;
  if (!s2) return s1.length;
  if (s1.length < s2.length) return fastLevenshtein(s2, s1);

  let prev = [];
  for (let j = 0; j <= s2.length; j++) prev[j] = j;

  for (let i = 0; i < s1.length; i++) {
    const curr = [i + 1];
    for (let j = 0; j < s2.length; j++) {
      const cost = s1[i] === s2[j] ? 0 : 1;
      curr[j + 1] = Math.min(
        curr[j] + 1,       // insertion
        prev[j + 1] + 1,   // deletion
        prev[j] + cost     // substitution
      );
    }
    prev = curr;
  }
  return prev[s2.length];
};

/**
 * Hàm đối soát và tự động sửa lỗi quang học qua Danh mục Master Data 478 SKU
 * @param {string} raw - Chuỗi quét được từ camera hoặc máy quét
 * @param {string} standardSku - Mã SKU chuẩn hiện tại của Pallet (nếu có)
 * @returns {string|null} - Mã chuẩn trong Danh mục, hoặc null nếu không hợp lệ
 */
export const matchCatalogSku = (raw, standardSku = '') => {
  if (!raw) return null;
  let str = String(raw).trim().toUpperCase();

  // Khử dấu và ký tự lạ, chuẩn hóa gạch nối
  str = str.replace(/[‐-―−－]/g, '-').replace(/\s+/g, '');

  // 1. Nếu trùng khớp chính xác 100% trong Danh mục:
  if (PRODUCT_SKU_SET.has(str)) {
    return str;
  }

  // 2. Khắc phục nhòe đuôi màu sơn qua Bảng Ánh Xạ Quang Học:
  // Ví dụ: '17-2621-W5T' -> '17-2621-WHT', '17-2621-W1T' -> '17-2621-WHT'
  let tailFixed = str;
  const parts = str.split('-');
  if (parts.length >= 2) {
    const rawTail = parts[parts.length - 1];
    if (OPTICAL_COLOR_MAP[rawTail]) {
      const mappedTail = OPTICAL_COLOR_MAP[rawTail];
      const cand = [...parts.slice(0, parts.length - 1), mappedTail].join('-');
      if (PRODUCT_SKU_SET.has(cand)) {
        return cand;
      }
      tailFixed = cand;
    }
  }

  // Khắc phục trực tiếp các đuôi phổ biến bị cắt cụt hoặc nhòe:
  tailFixed = tailFixed
    .replace(/-W5T$/, '-WHT')
    .replace(/-W1T$/, '-WHT')
    .replace(/-W5$/, '-WHT')
    .replace(/-W1$/, '-WHT')
    .replace(/-8LK$/, '-BLK')
    .replace(/-6RY$/, '-GRY')
    .replace(/-E5P$/, '-ESP')
    .replace(/-W0A$/, '-WOA');

  if (PRODUCT_SKU_SET.has(tailFixed)) {
    return tailFixed;
  }

  // 3. Khắc phục nhòe khe hở dấu '-' (mất dấu '-' hoặc '-2' thành '4', '-' thành '7'):
  // TH A: '174621-WHT' -> '17-2621-WHT'
  const m1 = tailFixed.match(/^(\d{2})4(\d{3,4}-[A-Z0-9]+)$/);
  if (m1) {
    let cand = `${m1[1]}-2${m1[2]}`;
    const cp = cand.split('-');
    if (cp.length === 3 && OPTICAL_COLOR_MAP[cp[2]]) {
      cand = `${cp[0]}-${cp[1]}-${OPTICAL_COLOR_MAP[cp[2]]}`;
    }
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }

  // TH B: '1772621-WHT' -> '17-2621-WHT'
  const m2 = tailFixed.match(/^(\d{2})7(\d{4}-[A-Z0-9]+)$/);
  if (m2) {
    let cand = `${m2[1]}-${m2[2]}`;
    const cp = cand.split('-');
    if (cp.length === 3 && OPTICAL_COLOR_MAP[cp[2]]) {
      cand = `${cp[0]}-${cp[1]}-${OPTICAL_COLOR_MAP[cp[2]]}`;
    }
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }

  // TH C: '172621-WHT' -> '17-2621-WHT'
  const m3 = tailFixed.match(/^(\d{2})(\d{4})-([A-Z0-9]+)$/);
  if (m3) {
    const color = OPTICAL_COLOR_MAP[m3[3]] || m3[3];
    const cand = `${m3[1]}-${m3[2]}-${color}`;
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }

  // TH D: '17-2621WHT' -> '17-2621-WHT'
  const m4 = tailFixed.match(/^(\d{2})-(\d{4})([A-Z0-9]+)$/);
  if (m4) {
    const color = OPTICAL_COLOR_MAP[m4[3]] || m4[3];
    const cand = `${m4[1]}-${m4[2]}-${color}`;
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }

  // TH E: Mất cả 2 dấu '-' như '174621WHT' hoặc '172621WHT'
  const m5 = tailFixed.match(/^(\d{2})4(\d{3})([A-Z0-9]+)$/);
  if (m5) {
    const color = OPTICAL_COLOR_MAP[m5[3]] || m5[3];
    const cand = `${m5[1]}-2${m5[2]}-${color}`;
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }
  const m6 = tailFixed.match(/^(\d{2})(\d{4})([A-Z0-9]+)$/);
  if (m6) {
    const color = OPTICAL_COLOR_MAP[m6[3]] || m6[3];
    const cand = `${m6[1]}-${m6[2]}-${color}`;
    if (PRODUCT_SKU_SET.has(cand)) return cand;
  }

  // 4. Đối soát ưu tiên cao với Mã chuẩn của Pallet (nếu có standardSku):
  // Ví dụ mã chuẩn là '17-2621-WHT':
  // Quét ra '17-2621-W5T', '17-2621-W5', '17-2621-W', '174621-W5T'
  if (standardSku && PRODUCT_SKU_SET.has(standardSku)) {
    const stdParts = standardSku.split('-');
    if (stdParts.length === 3) {
      const modelPrefix = `${stdParts[0]}-${stdParts[1]}-`;
      const blurPrefix = stdParts[1].startsWith('2') ? `${stdParts[0]}4${stdParts[1].slice(1)}-` : null;
      const stdColor = stdParts[2];

      if (str.startsWith(modelPrefix)) {
        const rawTail = str.slice(modelPrefix.length);
        if (OPTICAL_COLOR_MAP[rawTail] === stdColor || fastLevenshtein(rawTail, stdColor) <= 1) {
          return standardSku;
        }
      } else if (blurPrefix && str.startsWith(blurPrefix)) {
        const rawTail = str.slice(blurPrefix.length);
        if (OPTICAL_COLOR_MAP[rawTail] === stdColor || fastLevenshtein(rawTail, stdColor) <= 1) {
          return standardSku;
        }
      }

      // Khoảng cách sai lệch tổng thể <= 2 so với standardSku
      if (fastLevenshtein(str, standardSku) <= 2 || fastLevenshtein(tailFixed, standardSku) <= 2) {
        return standardSku;
      }
    }
  }

  // 5. Fallback Levenshtein đối soát với toàn bộ 478 SKU trong Danh mục:
  // Nếu sai lệch tối đa 1 ký tự (ví dụ: '17-2621-W5T' -> '17-2621-WHT' khoảng cách là 1)
  let bestSku = null;
  let minDistance = 999;
  const targetStr = tailFixed || str;

  for (let i = 0; i < PRODUCT_SKU_LIST.length; i++) {
    const sku = PRODUCT_SKU_LIST[i];
    const dist = fastLevenshtein(targetStr, sku);
    if (dist < minDistance) {
      minDistance = dist;
      bestSku = sku;
      if (dist === 0) break;
    }
  }

  if (minDistance <= 1 && bestSku) {
    return bestSku;
  }

  return null;
};
